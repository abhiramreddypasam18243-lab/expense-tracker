"""Benchmark the learned categoriser on synthetic labelled data (spec 5.1).

Usage:
    python tools/evaluate_model.py                 # writes docs/model-evaluation.md
    python tools/evaluate_model.py --out report.md --seeds 10

Synthetic data only (privacy rule). Numbers on real statements will differ; the app's
Settings → Smart categories tab reports the score on the user's own data.
"""

from __future__ import annotations

import argparse
import statistics
import sys
import time
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from expenses import learn  # noqa: E402
from tools.make_synthetic import AMBIGUOUS_WORDS, CATEGORY_WORDS, INCOME_CATEGORIES, generate_labelled  # noqa: E402

KINDS = {c: ("income" if c in INCOME_CATEGORIES else "expense") for c in CATEGORY_WORDS}
NAMES = {c: c for c in CATEGORY_WORDS}
_WORDS = sorted(
    [(w, c) for c, ws in CATEGORY_WORDS.items() for w in ws] + [(w, None) for w in AMBIGUOUS_WORDS],
    key=lambda pair: -len(pair[0]),
)


def examples(seed: int) -> list[learn.Example]:
    return [learn.Example(d, m, a, c) for m, d, c, a in generate_labelled(seed)]


def category_word(merchant: str) -> str:
    return next(w for w, _ in _WORDS if merchant.endswith(w))


def vocabulary_breakdown(seed: int, classifier: str = "nb") -> dict[str, tuple[int, int]]:
    """Test accuracy split by WHY a merchant is hard: {group: (correct, total)}.

    known word   — its category word appeared in a training merchant
    new word     — the word never appeared in training (no model can know it)
    ambiguous    — no category word at all (random label)
    """
    data = examples(seed)
    train_part, test_part = learn._split(data)
    model = learn.train(train_part, KINDS, classifier)
    seen = {category_word(e.merchant) for e in train_part}
    out: dict[str, list[int]] = {"known word": [0, 0], "new word": [0, 0], "ambiguous": [0, 0]}
    predictions = model.predict_many([e.text for e in test_part], [e.amount_minor for e in test_part])
    for e, p in zip(test_part, predictions, strict=True):
        word = category_word(e.merchant)
        group = "ambiguous" if word in AMBIGUOUS_WORDS else ("known word" if word in seen else "new word")
        out[group][0] += int(p is not None and p[0] == e.label)
        out[group][1] += 1
    return {k: (v[0], v[1]) for k, v in out.items()}


def compare(seeds: range) -> list[tuple[str, float, float, float, float, float]]:
    """(classifier, mean accuracy, sd, coverage@default, accuracy@default, seconds) over many benchmarks."""
    rows = []
    for name in learn.CLASSIFIERS:
        acc, cov, prec, secs = [], [], [], []
        for seed in seeds:
            start = time.perf_counter()
            ev = learn.evaluate(examples(seed), KINDS, NAMES, classifier=name)
            secs.append(time.perf_counter() - start)
            acc.append(ev.accuracy)
            cov.append(ev.coverage)
            prec.append(ev.accuracy_at_threshold or 0.0)
        rows.append(
            (
                name,
                statistics.mean(acc),
                statistics.stdev(acc),
                statistics.mean(cov),
                statistics.mean(prec),
                statistics.mean(secs),
            )
        )
    return rows


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{x * 100:.1f} %"


def report(seeds: int = 10, main_seed: int = 7) -> str:
    ev = learn.evaluate(examples(main_seed), KINDS, NAMES)
    lines = [
        "# Learned categorisation — evaluation",
        "",
        f"Generated by `python tools/evaluate_model.py` on {date.today().isoformat()}. "
        "**Synthetic data only** (privacy rule): invented merchants whose names carry category words, plus "
        "~10 % deliberately ambiguous names. Real-statement accuracy will differ; the app's *Settings → Smart "
        "categories* tab reports the score on your own data.",
        "",
        "## Method",
        "",
        "- Features: TF-IDF word 1–2-grams + character 3–5-grams of the cleaned narration "
        "(digits and payment-channel words removed) + a debit/credit marker.",
        "- Domain constraint: debits only get expense/transfer categories, credits only income/transfer.",
        f"- **Merchant-grouped split** ({int((1 - learn.TEST_SHARE) * 100)} / {int(learn.TEST_SHARE * 100)}): "
        "no merchant is in both train and test, so every test row is a merchant the model has **never seen**.",
        "",
        f"## Classifier comparison ({seeds} benchmarks, seeds 1–{seeds})",
        "",
        f"| Classifier | Accuracy (unseen merchants) | Labelled at threshold {learn.DEFAULT_THRESHOLD:.2f} "
        "| Accuracy of those | Time per evaluation |",
        "|---|---|---|---|---|",
    ]
    label = {
        "nb": "Complement Naive Bayes (**used**)",
        "logreg": "Logistic regression",
        "svm": "Linear SVM (calibrated)",
    }
    for name, acc, sd, cov, prec, secs in compare(range(1, seeds + 1)):
        lines.append(
            f"| {label[name]} | {_pct(acc)} ± {sd * 100:.1f} | {_pct(cov)} | {_pct(prec)} | {secs:.2f} s |"
        )
    lines += [
        "",
        "All three are close in accuracy; Complement Naive Bayes labels the most rows at the default threshold "
        "with comparable accuracy and is the fastest, so the app uses it.",
        "",
        f"## Main benchmark (seed {main_seed})",
        "",
        f"- Training: {ev.n_train} transactions from {ev.train_merchants} merchants; "
        f"test: {ev.n_test} transactions from {ev.test_merchants} **other** merchants "
        f"(shared merchants: {ev.shared_merchants}).",
        f"- Accuracy (always guessing): **{_pct(ev.accuracy)}**; macro-F1 {ev.macro_f1:.3f}.",
        f"- At the default threshold {ev.threshold:.2f}: labels **{_pct(ev.coverage)}** of rows, "
        f"**{_pct(ev.accuracy_at_threshold)}** of them correct; the rest stay Uncategorised for the user.",
        "",
        "### Why it gets some wrong",
        "",
        "| Test merchants whose category word… | Correct | Accuracy |",
        "|---|---|---|",
    ]
    for group, (ok, total) in vocabulary_breakdown(main_seed).items():
        lines.append(f"| {group} | {ok} / {total} | {_pct(ok / total if total else None)} |")
    lines += [
        "",
        "When the category word was seen in training the model is almost always right; the errors are words it "
        "has never seen (no model can know a new word's meaning without an example — one manual correction "
        "teaches it) and deliberately ambiguous names. Some words are shared between categories "
        "(TRAVELS: cabs vs tours), which is realistic.",
        "",
        "### Confidence threshold trade-off",
        "",
        "| Threshold | Rows labelled | Accuracy of those |",
        "|---|---|---|",
    ]
    lines += [f"| {t:.2f} | {_pct(c)} | {_pct(a)} |" for t, c, a in ev.thresholds]
    lines += [
        "",
        "### Learning curve",
        "",
        "| Training examples | Accuracy on unseen merchants |",
        "|---|---|",
    ]
    lines += [f"| {n} | {_pct(a)} |" for n, a in ev.curve]
    lines += [
        "",
        "### Per category",
        "",
        "| Category | Precision | Recall | Test rows |",
        "|---|---|---|---|",
    ]
    lines += [f"| {s.name} | {_pct(s.precision)} | {_pct(s.recall)} | {s.support} |" for s in ev.per_category]
    lines += ["", "### Confusion matrix (rows = true, columns = predicted)", ""]
    short = [n.split(" ")[0][:8] for n in ev.confusion_labels]
    lines.append("| | " + " | ".join(short) + " |")
    lines.append("|---" * (len(short) + 1) + "|")
    for name, row in zip(short, ev.confusion, strict=True):
        lines.append(f"| **{name}** | " + " | ".join(str(v) if v else "·" for v in row) + " |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "docs" / "model-evaluation.md"))
    parser.add_argument("--seeds", type=int, default=10)
    args = parser.parse_args(argv)
    Path(args.out).write_text(report(args.seeds), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
