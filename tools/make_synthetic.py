"""Synthetic bank-statement generator — the ONLY source of test/demo data.

Usage:
    python tools/make_synthetic.py --seed 42 --layout amount --months 6 --out data/synthetic.csv

Layouts:
    amount        Date (YYYY-MM-DD), Description, Amount (signed; debit negative)
    debit_credit  bank-style preamble, then Txn Date (DD/MM/YYYY), Narration,
                  Withdrawal Amt, Deposit Amt (comma-grouped)

All money is generated as integer paise; no floats are used.
Reference numbers are short "SYN" codes so nothing looks like a real account.
"""

from __future__ import annotations

import argparse
import calendar
import csv
import io
import random
from datetime import date

# (description template, min paise, max paise). {ref} -> short synthetic reference.
EXPENSE_TEMPLATES = [
    ("UPI/{ref}/SWIGGY/OKAXIS/Food order", 15_000, 90_000),
    ("UPI-ZOMATO-{ref}-PAYMENT", 18_000, 85_000),
    ("UPI/{ref}/CHAI POINT/OKSBI/Tea", 2_000, 2_000),
    ("POS 4821 BIG BAZAAR", 80_000, 450_000),
    ("UPI/{ref}/BLINKIT/YBL/Groceries", 30_000, 180_000),
    ("UPI-UBER INDIA-{ref}-RIDE", 12_000, 65_000),
    ("UPI/{ref}/OLA CABS/OKICICI/Ride", 10_000, 55_000),
    ("POS 7310 AMAZON RETAIL", 50_000, 600_000),
    ("UPI-FLIPKART-{ref}-ORDER", 40_000, 500_000),
    ("BILLPAY BESCOM ELECTRICITY {ref}", 90_000, 250_000),
    ("UPI/{ref}/JIO PREPAID/PAYTM/Recharge", 29_900, 29_900),
    ("POS 1102 PVR CINEMAS", 35_000, 120_000),
    ("UPI-NETFLIX-{ref}-SUBSCRIPTION", 64_900, 64_900),
    ("POS 5521 APOLLO PHARMACY", 15_000, 160_000),
    ("UPI/{ref}/COURSERA/OKHDFC/Course", 199_900, 399_900),
    ("ATM WDL {ref} SYN BRANCH", 200_000, 1_000_000),
]

# Rare, very large purchases so the anomaly detector has something to find.
OUTLIER_TEMPLATES = [
    ("UPI/{ref}/SWIGGY/OKAXIS/Party order", 840_000, 840_000),
    ("POS 7310 AMAZON RETAIL", 6_500_000, 6_500_000),
]


def _ref(rng: random.Random) -> str:
    return f"SYN{rng.randint(0, 999_999):06d}"


def _plain(paise: int) -> str:
    """Positive paise -> '1234.50'."""
    return f"{paise // 100}.{paise % 100:02d}"


def _grouped(paise: int) -> str:
    """Positive paise -> '1,234.50' (Western grouping, as many banks export)."""
    return f"{paise // 100:,}.{paise % 100:02d}"


def _add_months(start: date, n: int) -> tuple[int, int]:
    total = start.year * 12 + (start.month - 1) + n
    return total // 12, total % 12 + 1


def generate_rows(seed: int, months: int = 6, start: date = date(2026, 1, 1)) -> list[tuple[date, str, int]]:
    """Return (date, description, signed paise) rows, sorted by date."""
    rng = random.Random(seed)
    rows: list[tuple[date, str, int]] = []
    for m in range(months):
        year, month = _add_months(start, m)
        last_day = calendar.monthrange(year, month)[1]

        def day(rng=rng, year=year, month=month, last_day=last_day) -> date:
            return date(year, month, rng.randint(1, last_day))

        rows.append((date(year, month, 1), "NEFT SALARY ACME SYNTHETIC LTD", 8_500_000))
        rows.append((date(year, month, 3), f"IMPS RENT {_ref(rng)} SYN LANDLORD", -2_200_000))
        rows.append((day(), f"IMPS SELF TRANSFER {_ref(rng)}", -500_000))
        if rng.random() < 0.3:
            refund = rng.randint(20_000, 150_000)
            rows.append((day(), f"REFUND AMAZON RETAIL {_ref(rng)}", refund))

        for _ in range(rng.randint(35, 50)):
            template, low, high = rng.choice(EXPENSE_TEMPLATES)
            rows.append((day(), template.format(ref=_ref(rng)), -rng.randint(low, high)))

        # Two genuine identical tea purchases on the same day (same ref-free text).
        tea_day = day()
        rows.append((tea_day, "POS 0042 CHAI POINT", -2_000))
        rows.append((tea_day, "POS 0042 CHAI POINT", -2_000))

        if m == months - 1:
            for template, low, high in OUTLIER_TEMPLATES:
                rows.append((day(), template.format(ref=_ref(rng)), -rng.randint(low, high)))

    rows.sort(key=lambda r: r[0])
    return rows


def generate_csv(seed: int, layout: str = "amount", months: int = 6, start: date = date(2026, 1, 1)) -> str:
    rows = generate_rows(seed, months, start)
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    if layout == "amount":
        buf.write("# SYNTHETIC DATA - generated by tools/make_synthetic.py\n")
        writer.writerow(["Date", "Description", "Amount"])
        for d, desc, paise in rows:
            sign = "-" if paise < 0 else ""
            writer.writerow([d.isoformat(), desc, sign + _plain(abs(paise))])
    elif layout == "debit_credit":
        buf.write("SYNTHETIC BANK LTD - Statement of Account\n")
        buf.write("Account: SYN-XXXX-0001\n")
        buf.write(f"Period: {rows[0][0]:%d/%m/%Y} to {rows[-1][0]:%d/%m/%Y}\n")
        buf.write("\n")
        writer.writerow(["Txn Date", "Narration", "Withdrawal Amt", "Deposit Amt"])
        for d, desc, paise in rows:
            debit = _grouped(-paise) if paise < 0 else ""
            credit = _grouped(paise) if paise > 0 else ""
            writer.writerow([f"{d:%d/%m/%Y}", desc, debit, credit])
    else:
        raise ValueError(f"unknown layout: {layout}")
    return buf.getvalue()


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Generate a synthetic bank statement CSV.")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--layout", choices=["amount", "debit_credit"], default="amount")
    parser.add_argument("--months", type=int, default=6)
    parser.add_argument("--out", required=True, help="output CSV path")
    args = parser.parse_args(argv)
    text = generate_csv(args.seed, args.layout, args.months)
    with open(args.out, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
